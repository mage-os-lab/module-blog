<?php

declare(strict_types=1);

namespace MageOS\Blog\Model\Url;

use Magento\UrlRewrite\Model\OptionProvider;
use Magento\UrlRewrite\Model\UrlFinderInterface;
use Magento\UrlRewrite\Model\UrlPersistInterface;
use Magento\UrlRewrite\Service\V1\Data\UrlRewrite;
use Magento\UrlRewrite\Service\V1\Data\UrlRewriteFactory;

/**
 * Redirect rows that keep an entity's earlier URLs working once its request path changes.
 *
 * A request path changes when the URL key or slug is edited, and when a permalink segment is
 * reconfigured. Either way every path the entity was served or redirected under on a store gets
 * a redirect to the path it has now on that store.
 *
 * UrlPersistInterface::replace() deletes every row of the entity on a store that it is not handed,
 * so redirects written by an earlier save are rebuilt here as well. Otherwise they would last only
 * until the next save. Each one points straight at the current path, so a chain of renames never
 * becomes a chain of redirects.
 */
class RedirectBuilder
{
    public function __construct(
        private readonly UrlFinderInterface $urlFinder,
        private readonly UrlRewriteFactory $urlRewriteFactory,
        private readonly UrlPersistInterface $urlPersist,
    ) {
    }

    /**
     * @param UrlRewrite[] $newRows the entity's current rows, one per store it is visible on
     * @return UrlRewrite[]
     */
    public function build(string $entityType, int $entityId, array $newRows): array
    {
        $currentPaths = [];
        foreach ($newRows as $row) {
            $currentPaths[(int) $row->getStoreId()] = (string) $row->getRequestPath();
        }

        $existing = $this->urlFinder->findAllByData([
            UrlRewrite::ENTITY_TYPE => $entityType,
            UrlRewrite::ENTITY_ID => $entityId,
        ]);

        $redirects = [];
        foreach ($existing as $row) {
            $storeId = (int) $row->getStoreId();
            $oldPath = (string) $row->getRequestPath();
            // A store the entity left has no current path; StaleStoreRewriteCleaner drops its rows.
            if (!isset($currentPaths[$storeId]) || $oldPath === '' || $oldPath === $currentPaths[$storeId]) {
                continue;
            }

            $key = $storeId . '|' . $oldPath;
            if (isset($redirects[$key])) {
                continue;
            }

            $redirectType = (int) $row->getRedirectType();
            $redirect = $this->urlRewriteFactory->create();
            $redirect->setEntityType($entityType)
                ->setEntityId($entityId)
                ->setRequestPath($oldPath)
                ->setTargetPath($currentPaths[$storeId])
                ->setIsAutogenerated(0)
                ->setStoreId($storeId)
                ->setRedirectType($redirectType > 0 ? $redirectType : OptionProvider::PERMANENT);
            $redirects[$key] = $redirect;
        }

        return array_values($redirects);
    }

    /**
     * Drop redirects of other entities that sit on one of these new request paths.
     *
     * A redirect only stands in for a path an entity gave up, so a new owner takes it back. Without
     * this, a post could never take a URL key another post had before, because replace() refuses
     * a request path another entity holds on the same store.
     *
     * @param UrlRewrite[] $newRows
     */
    public function releasePathsHeldByRedirects(string $entityType, int $entityId, array $newRows): void
    {
        $pathsByStore = [];
        foreach ($newRows as $row) {
            $pathsByStore[(int) $row->getStoreId()][] = (string) $row->getRequestPath();
        }

        $release = [];
        foreach ($pathsByStore as $storeId => $paths) {
            $held = $this->urlFinder->findAllByData([
                UrlRewrite::ENTITY_TYPE => $entityType,
                UrlRewrite::REQUEST_PATH => $paths,
                UrlRewrite::STORE_ID => $storeId,
            ]);
            foreach ($held as $row) {
                if ((int) $row->getEntityId() !== $entityId && (int) $row->getRedirectType() > 0) {
                    $release[] = (int) $row->getUrlRewriteId();
                }
            }
        }

        if ($release !== []) {
            $this->urlPersist->deleteByData([UrlRewrite::URL_REWRITE_ID => $release]);
        }
    }
}
